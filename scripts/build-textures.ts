/**
 * Slices the Higgsfield texture sheets in assets/sheets into 16x16 tiles and writes
 * src/render/tiles.generated.ts. Run with `npm run textures`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { inflateSync } from 'node:zlib';
import { decodePng, encodeTile, sampleCell, type Fit } from '../src/tools/texture-pipeline';

interface CellSpec {
  name: string;
  fit?: Fit;
  key?: boolean;
  align?: 'center' | 'bottom';
  alpha?: number;
}
interface SheetSpec {
  file: string;
  grid: number;
  fit: Fit;
  key?: boolean;
  align?: 'center' | 'bottom';
  cells: (string | CellSpec | null)[];
}

const root = join(import.meta.dirname, '..');
const dir = join(root, 'assets/sheets');
const manifest = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8')) as { sheets: SheetSpec[] };

const tiles: Record<string, string> = {};
for (const sheet of manifest.sheets) {
  const img = decodePng(new Uint8Array(readFileSync(join(dir, sheet.file))), (d) => new Uint8Array(inflateSync(d)));
  sheet.cells.forEach((entry, i) => {
    if (!entry) return;
    const spec: CellSpec = typeof entry === 'string' ? { name: entry } : entry;
    if (tiles[spec.name]) throw new Error(`Duplicate tile ${spec.name}`);
    const tile = sampleCell(img, sheet.grid, i % sheet.grid, Math.floor(i / sheet.grid), {
      fit: spec.fit ?? sheet.fit,
      key: spec.key ?? sheet.key,
      align: spec.align ?? sheet.align,
      alpha: spec.alpha,
    });
    tiles[spec.name] = encodeTile(tile);
  });
}

const body = Object.entries(tiles)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, b64]) => `  ${name}: '${b64}',`)
  .join('\n');
writeFileSync(
  join(root, 'src/render/tiles.generated.ts'),
  `// Generated by scripts/build-textures.ts from assets/sheets — do not edit by hand.\n` +
    `// 16x16 RGBA tiles, base64-encoded.\n` +
    `export const GENERATED_TILES: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`Wrote ${Object.keys(tiles).length} tiles.`);
